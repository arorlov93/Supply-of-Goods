/* Один сайт по одному адресу.
 *
 * И ispgroupgc.com, и www.ispgroupgc.com отдавали код 200 с одинаковым
 * содержимым. Для поисковика это два разных сайта с полным дублированием:
 * вес страницы делится надвое, а какая из версий попадёт в выдачу, решает
 * он, а не мы. Канонические ссылки это смягчают, но не отменяют.
 *
 * Та же беда, и хуже, с адресами Pages. Проверено запросом: сайт целиком
 * открывался на ispgroupgc.pages.dev с кодом 200 и с разрешением на
 * индексацию. Вдобавок каждая выкладка заводит собственный адрес вида
 * 79c1991b.ispgroupgc.pages.dev, и все они живут вечно. То есть копий
 * сайта не две, а столько, сколько было выкладок, и ссылка на любую из
 * них уводит вес с настоящего домена.
 *
 * Поэтому правило общее: всё, что не апекс, едет на апекс.
 *
 * Настраивается это обычно правилом в зоне Cloudflare, но прав на зону у
 * нашего токена нет. Здесь то же самое делается на самом Pages: корневое
 * middleware получает каждый запрос, включая запросы к статике, и отдаёт
 * постоянный редирект на апекс с сохранением пути и строки запроса.
 *
 * 301, а не 302: редирект постоянный, и поисковик должен перенести вес на
 * апекс, а не держать обе версии в индексе.
 *
 * Здесь же висит дожим писем по заявкам, см. _queue.js. Место неочевидное,
 * но единственное доступное: Pages Functions не умеют работать по
 * расписанию, а заявка, по которой письмо не ушло с первой попытки, должна
 * уйти сама, без человека. Дожим цепляется только к запросам страниц, не к
 * картинкам и стилям, и работает после ответа, поэтому посетитель его не
 * ждёт ни на миллисекунду.
 */
import { drainOne } from "./_queue.js";
import { fxCached, withFx } from "./_fx.js";

export async function onRequest(context) {
  const url = new URL(context.request.url);

  const APEX = "ispgroupgc.com";
  const host = url.hostname.toLowerCase();

  if (host !== APEX) {
    url.hostname = APEX;
    return new Response(null, {
      status: 301,
      headers: {
        Location: url.toString(),
        // редирект можно кэшировать: он не изменится
        "Cache-Control": "public, max-age=3600",
      },
    });
  }

  /* Только страницы: на одну страницу приходится десяток запросов к
     статике, и дёргать очередь на каждый значит просто биться в предел
     частоты ретранслятора. Проверка по Accept, а не по расширению: так
     попадают и адреса без расширения, которыми у нас набрана вся
     навигация. */
  const wantsPage =
    context.request.method === "GET" &&
    (context.request.headers.get("accept") || "").includes("text/html");

  if (wantsPage && context.env.DB && typeof context.waitUntil === "function") {
    context.waitUntil(
      drainOne(context.env).catch((e) =>
        console.log("дожим упал:", String((e && e.message) || e).slice(0, 160))
      )
    );
  }

  const res = await context.next();

  /* Ежедневная часть страницы индекса подставляется здесь, в ответе, а не
     при сборке. Причина простая: сборка требует выкладки, выкладка требует
     токена, а токен живёт не дольше той сессии, которой его дали. Так
     страница обновляется сама, и нажимать некому не нужно.

     Ответ при этом никогда не ждёт Европейский центробанк: если свежих
     курсов в кэше нет, уходит то, что запечено при сборке, а за новыми
     идём после ответа. Чужая служба не должна уметь замедлить наш сайт. */
  if (wantsPage && /^\/landed-price-index(\.html)?$/.test(url.pathname)) {
    try {
      const fx = await fxCached(context);
      if (fx && (res.headers.get("content-type") || "").includes("text/html")) {
        return withFx(res, fx);
      }
    } catch (e) {
      console.log("fx: подстановка не вышла,", String((e && e.message) || e).slice(0, 160));
    }
  }

  return res;
}
