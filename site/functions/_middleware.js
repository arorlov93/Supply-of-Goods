/* Один сайт по одному адресу.
 *
 * И ispgroupgc.com, и www.ispgroupgc.com отдавали код 200 с одинаковым
 * содержимым. Для поисковика это два разных сайта с полным дублированием:
 * вес страницы делится надвое, а какая из версий попадёт в выдачу, решает
 * он, а не мы. Канонические ссылки это смягчают, но не отменяют.
 *
 * Настраивается это обычно правилом в зоне Cloudflare, но прав на зону у
 * нашего токена нет. Здесь то же самое делается на самом Pages: корневое
 * middleware получает каждый запрос, включая запросы к статике, и отдаёт
 * постоянный редирект на апекс с сохранением пути и строки запроса.
 *
 * 301, а не 302: редирект постоянный, и поисковик должен перенести вес на
 * апекс, а не держать обе версии в индексе.
 */
export async function onRequest(context) {
  const url = new URL(context.request.url);

  if (url.hostname.toLowerCase().startsWith("www.")) {
    url.hostname = url.hostname.slice(4);
    return new Response(null, {
      status: 301,
      headers: {
        Location: url.toString(),
        // редирект можно кэшировать: он не изменится
        "Cache-Control": "public, max-age=3600",
      },
    });
  }

  return context.next();
}
