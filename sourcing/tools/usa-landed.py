#!/usr/bin/env python3
"""Сравнение ввозной нагрузки в США по товарным группам, сентябрь 2026.

Ставки:
  Section 232 — 50% на изделия преимущественно из стали/алюминия/меди,
                25% на производные (derivative), на ПОЛНУЮ таможенную стоимость.
                Исключение: если вес металла < 15% общего веса товара.
  Section 301 — 12.5% на большинство товаров происхождением Турция (с 24.07.2026).
  AD/CVD      — отдельно, по конкретным приказам Commerce.
  USMCA       — беспошлинно по MFN для соответствующих товаров из Мексики,
                но НЕ освобождает от Section 232.
"""

FOB = 1000.0        # условная база, USD за единицу стоимости, для сравнимости
FREIGHT = 120.0     # океанский фрахт + страховка, оценка


def landed(name, mfn=0.0, s232=0.0, s301=0.0, adcvd=0.0, note=""):
    cif = FOB + FREIGHT
    duty = cif * (mfn + s232 + s301 + adcvd)
    total = cif + duty
    return name, cif, duty, total, (total / cif - 1) * 100, note


ROWS = [
    # --- СТАЛЬ И МЕТАЛЛ ---
    landed("Стальная труба, Турция", mfn=0.0, s232=0.50, s301=0.125, adcvd=0.20,
           note="CWP: AD/CVD действует; ставка 20% взята как ориентир ESTIMATE"),
    landed("Арматура (rebar), Турция", mfn=0.0, s232=0.50, s301=0.125, adcvd=0.07,
           note="CVD 6.58-7.71% подтверждён, плюс AD"),
    landed("Стальная труба, Мексика", mfn=0.0, s232=0.50,
           note="USMCA от Section 232 НЕ освобождает"),
    landed("Алюминиевый профиль, Турция", mfn=0.0, s232=0.50, s301=0.125),
    landed("Металлическое изделие (derivative)", mfn=0.0, s232=0.25, s301=0.125,
           note="25% на полную стоимость, а не на металл"),

    # --- НЕМЕТАЛЛ: металла < 15% веса, Section 232 НЕ ПРИМЕНЯЕТСЯ ---
    landed("Мрамор/травертин, Турция", mfn=0.0, s301=0.125,
           note="MFN на большинство natural stone = free; AD/CVD нет"),
    landed("Керамогранит/плитка, Турция", mfn=0.085, s301=0.125,
           note="MFN ориентировочно 8.5% ESTIMATE; AD/CVD на Турцию нет"),
    landed("Кварцевый камень, Турция", mfn=0.0, s301=0.125, adcvd=0.05,
           note="AD/CVD ПРОДЛЁН 15.01.2026 — ниша закрыта"),
    landed("Санфаянс, Турция", mfn=0.055, s301=0.125, note="MFN ESTIMATE"),
    landed("Камень/плитка, Мексика (USMCA)", mfn=0.0, s301=0.0,
           note="USMCA: беспошлинно, Section 232 неприменим"),
    landed("Камень, Бразилия", mfn=0.0, s301=0.0,
           note="ставка по Бразилии требует проверки на дату сделки"),
]

print("=" * 104)
print("ВВОЗНАЯ НАГРУЗКА В США, сентябрь 2026 (база FOB 1000 + фрахт 120 = CIF 1120)")
print("=" * 104)
print(f"{'товар':34}{'CIF':>8}{'пошлины':>10}{'landed':>9}{'надбавка':>11}  комментарий")
for n, cif, duty, tot, pct, note in ROWS:
    print(f"{n:34}{cif:8.0f}{duty:10.0f}{tot:9.0f}{pct:10.1f}%  {note[:44]}")

print()
print("=" * 104)
print("ЧТО ЭТО ЗНАЧИТ ДЛЯ МАРЖИ")
print("=" * 104)
print("Чтобы продать в США с наценкой 20% к landed, цена продажи должна быть:")
for n, cif, duty, tot, pct, note in ROWS:
    print(f"  {n:34} {tot*1.2:8.0f} USD   (против {cif*1.2:6.0f} без барьеров)")
