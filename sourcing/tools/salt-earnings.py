#!/usr/bin/env python3
"""Сколько реально можно заработать на соли: лоты -> сезон -> год."""
BUY, VAT, USN = 4500, 0.22, 0.15

LOTS = [("Самара", 6_020_000, 700, 0.10),
        ("Венёв", 1_106_000, 140, 0.10),
        ("Саратов", 4_518_000, 600, 0.05),
        ("Димитровград", 4_440_000, 600, 0.05)]


def gross(price_per_t, tons, delivery=0, discount=0.0):
    """Валовая прибыль по лоту, ₽. discount — падение на аукционе."""
    p = price_per_t * (1 - discount)
    return (p / (1 + VAT) - BUY - delivery / (1 + VAT)) * tons


print("=" * 70)
print("1. ЧЕТЫРЕ ЛОТА: как падение на аукционе съедает прибыль")
print("=" * 70)
print(f"{'снижение':>10}{'доставка 0':>14}{'500 ₽/т':>13}{'1000 ₽/т':>13}{'1500 ₽/т':>13}")
for disc in (0, 0.05, 0.10, 0.15, 0.20):
    row = []
    for dl in (0, 500, 1000, 1500):
        g = sum(gross(n / t, t, dl, disc) for _, n, t, _ in LOTS)
        row.append(g)
    print(f"{disc*100:9.0f}%" + "".join(f"{x/1e6:13.2f}" for x in row))
print("\n(2 040 т суммарно; цифры — млн ₽ валовой прибыли)")

print("\n" + "=" * 70)
print("2. РЕАЛЬНОСТЬ: ты не выиграешь все лоты")
print("=" * 70)
print(f"{'выиграл':>22}{'вал.приб.':>12}{'чистыми':>11}  допущения")
opex = 400_000
for label, lots, disc, dl in [
        ("1 лот (Димитровград)", [LOTS[3]], 0.10, 500),
        ("1 лот (Самара)", [LOTS[0]], 0.10, 500),
        ("2 лота (Сам.+Сар.)", [LOTS[0], LOTS[2]], 0.10, 500),
        ("все 4", LOTS, 0.10, 500),
        ("все 4, плечо 1000", LOTS, 0.10, 1000)]:
    g = sum(gross(n / t, t, dl, disc) for _, n, t, _ in lots)
    net = (g - opex) * (1 - USN)
    print(f"{label:>22}{g/1e6:12.2f}{net/1e6:11.2f}  сниж.{disc*100:.0f}%, дост.{dl} ₽/т")
print(f"\nopex принят {opex:,} ₽ на сделку".replace(",", " "))

print("\n" + "=" * 70)
print("3. СЕЗОН ЦЕЛИКОМ: зона короткого плеча")
print("=" * 70)
ZONE1 = 193_000_000          # НМЦК живых лотов зоны 1, найдено 25.09.2026
print(f"НМЦК живых лотов зоны 1: {ZONE1/1e6:.0f} млн ₽ (21 лот)")
print(f"{'доля выигрыша':>16}{'выручка':>12}{'вал.приб.':>12}{'чистыми':>11}")
for share in (0.05, 0.10, 0.15, 0.25):
    rev = ZONE1 * share * 0.90                 # с учётом снижения 10%
    tons = rev / (7900 * 0.90)                 # средняя цена ~7900 ₽/т
    g = (rev / (1 + VAT)) - BUY * tons - (500 / (1 + VAT)) * tons
    net = (g - opex * max(1, share * 21)) * (1 - USN)
    print(f"{share*100:15.0f}%{rev/1e6:12.1f}{g/1e6:12.2f}{net/1e6:11.2f}")
print("\n(выручка и прибыль — млн ₽ за сезон, не за месяц)")

print("\n" + "=" * 70)
print("4. СХОДИТСЯ ЛИ С ЦЕЛЬЮ 1-1,5 МЛН/МЕС")
print("=" * 70)
print("Соляной сезон — примерно 4-5 месяцев отгрузок (окт-фев).")
for share, label in ((0.10, "10% зоны 1"), (0.25, "25% зоны 1")):
    rev = ZONE1 * share * 0.90
    tons = rev / (7900 * 0.90)
    g = (rev / (1 + VAT)) - BUY * tons - (500 / (1 + VAT)) * tons
    net = (g - opex * max(1, share * 21)) * (1 - USN)
    print(f"  {label}: {net/1e6:.2f} млн за сезон = {net/5/1e6:.2f} млн/мес "
          f"при размазывании на 12 мес: {net/12/1e6:.2f} млн/мес")
