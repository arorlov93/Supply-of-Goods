#!/usr/bin/env bash
# Ежедневное обновление индекса стоимости.
#
# Что обновляется и почему только это. Таможенная часть индекса годовая и
# менять её каждый день нечем. Меняется курс валюты, в которой продавец
# выставляет счёт: Европейский центробанк публикует справочные курсы
# каждый рабочий день. Это и есть честная ежедневная часть страницы.
#
# Что делает: забирает курсы, пересобирает страницу индекса, и если
# страница действительно изменилась, коммитит и выкладывает.
#
# Если страница не изменилась, ничего не коммитится и не выкладывается.
# Это важнее, чем кажется: ЕЦБ не публикует по выходным и праздникам, и
# ежедневная выкладка одного и того же только засоряет историю.
#
# Токен Cloudflare берётся из окружения. Без него скрипт доходит до
# выкладки, говорит об этом и выходит с кодом 2: правка остаётся в
# репозитории и уедет со следующей выкладкой.
#
# Запуск: bash tools/daily.sh
set -euo pipefail
cd "$(dirname "$0")/.."

say() { printf '\n\033[1m%s\033[0m\n' "$*"; }

say "1. Курсы ЕЦБ"
python3 tools/fx-daily.py

say "2. Пересборка страницы индекса"
python3 tools/offer-pages.py
python3 - <<'PY'
import sys; sys.path.insert(0, "tools")
import search_mod as S
n, size = S.build_index()
print(f"   индекс поиска: {n} страниц, {size/1024:.0f} КБ")
PY

if git diff --quiet -- site data; then
  say "3. Страница не изменилась, выкладка не нужна"
  echo "   ЕЦБ не публикует по выходным и праздникам, это нормальный исход"
  exit 0
fi

DATE=$(python3 -c "import json;print(json.load(open('data/fx.json'))['date'])")
say "3. Коммит"
git add -A site data
git commit -q -m "Индекс стоимости: курсы ЕЦБ на ${DATE}

Ежедневная часть страницы индекса. Таможенная часть годовая и меняться
каждый день не может, а курс валюты, в которой выставлен счёт, меняется,
и для импортёра это прямая статья расходов.

Co-Authored-By: Claude Opus 5 <noreply@anthropic.com>"
git push -u origin "$(git branch --show-current)"

if [ -z "${CLOUDFLARE_API_TOKEN:-}" ]; then
  say "4. Выкладка пропущена: нет CLOUDFLARE_API_TOKEN"
  echo "   Правка в репозитории и уедет со следующей выкладкой."
  exit 2
fi

say "4. Выкладка"
bash tools/deploy-cloudflare.sh
