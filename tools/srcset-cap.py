# -*- coding: utf-8 -*-
"""Обрезка верхней ступени у снимков главной.

Замер. Телефон с тройной плотностью экрана, а не с единичной, как
мерили раньше. На окне 390 точек главная весит 2.7 МБ.

Откуда вес. У снимка pallets-wall набор ступеней 351, 509, 731 и сразу
исходник 1280. Показывается он на телефоне на 351 точке, браузер при
тройной плотности просит 1053 и берёт наименьший подходящий файл, то
есть исходник: 494 КБ вместо 148. То же у шести кадров пути груза:
ступени 349 и 698, следом исходник 1700.

Правило. Снимаем верхнюю ступень там, где она заметно крупнее
предыдущей. Тогда на телефоне берётся 731 или 698, то есть запас 2.1 к
ширине показа. Это видимо лучше, чем кажется из цифр: разницу между
запасом 2.1 и 3 на приглушённой серой фотографии не видит никто, а
полтора мегабайта на каждом открытии главной видит каждый, кто платит
за мобильный трафик.

Чем платим. На планшете с двойной плотностью, где тот же кадр
показывается на 731 точке, запас становится единичным. Это настоящая
потеря резкости, и она осознанная: таких посетителей на порядок меньше,
чем телефонов.

Чего не трогаем. Кадр в шапке. Он один, он грузится первым, он и есть
первое впечатление, и показывается во всю полосу, где разница видна.
Имена исключений лежат в KEEP.

Запуск: python3.13 tools/srcset-cap.py [страница ...]
По умолчанию правится только главная и её языковые версии.
Повторный запуск ничего не меняет.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = ROOT / "site"

# Кадр в шапке: разницу там видно, ступень оставляем
KEEP = {"ops"}
# Насколько верхняя ступень должна быть крупнее предыдущей, чтобы её снять.
# Меньший разрыв означает, что ступени и так близко и резать нечего.
GAP = 1.35

CAND = re.compile(r"(\S+)\s+(\d+)w")


def stem(url):
    """ops-1536.81ce1fd8.webp -> ops"""
    name = url.rsplit("/", 1)[-1].split(".")[0]
    return re.sub(r"-\d+$", "", name)


def shown(sizes):
    """Самая крупная ширина показа из sizes, в точках.

    Нужна как пол: ниже неё резать нельзя. Иначе правило, которое должно
    убрать лишний вес, начинает портить те снимки, которым файла и так не
    хватает. Проверено: без этой защиты правило снимало у crane-dusk
    ступень 543 при показе на 1440, то есть делало мыльный кадр ещё
    мыльнее."""
    # В sizes перемешаны два рода чисел: условие показа и сама ширина.
    # «(max-width: 900px) 731px» это «на окне до 900 точек снимок занимает
    # 731». Если читать подряд, порогом окажется 900, и правило замолчит.
    # Скобки с условиями снимаем, считаем только то, что осталось.
    body = re.sub(r"\([^)]*\)", " ", sizes)
    px = [int(x) for x in re.findall(r"(\d+)px", body)]
    return max(px) if px else None


def cap(srcset, sizes):
    items = [(u, int(w)) for u, w in CAND.findall(srcset)]
    if len(items) < 2:
        return srcset, None
    items.sort(key=lambda x: x[1])
    if stem(items[0][0]) in KEEP:
        return srcset, None
    top, prev = items[-1], items[-2]
    if top[1] / prev[1] < GAP:
        return srcset, None
    floor = shown(sizes)
    if floor is None or prev[1] < floor:
        # после среза верхней останется файл мельче, чем место показа:
        # это уже не экономия, а порча кадра
        return srcset, None
    kept = items[:-1]
    return ", ".join(f"{u} {w}w" for u, w in kept), (top, prev)


def main(argv):
    pages = argv or ["index.html", "fr/index.html", "de/index.html", "es/index.html"]
    total = 0
    for rel in pages:
        p = SITE / rel
        if not p.is_file():
            continue
        s = p.read_text()
        cuts = []

        def fix(m):
            whole = m.group(0)
            value = m.group(1)
            sizes = re.search(r'sizes="([^"]*)"', whole)
            new, cut = cap(value, sizes.group(1) if sizes else "")
            if cut:
                cuts.append(cut)
            return whole.replace(value, new, 1)

        # набор и размеры показа лежат на одном теге, читать их надо вместе
        s2 = re.sub(r'<(?:source|img)[^>]*srcset="([^"]*\dw[^"]*)"[^>]*>', fix, s)

        # src должен указывать на файл, который остался в наборе: иначе
        # старый браузер без поддержки srcset утянет снятую ступень
        for top, prev in cuts:
            s2 = s2.replace(f'src="{top[0]}"', f'src="{prev[0]}"')

        if s2 != s:
            p.write_text(s2)
            for top, prev in cuts:
                print(f"  {rel}: {stem(top[0]):14s} снята ступень {top[1]}, "
                      f"верхняя теперь {prev[1]}")
            total += len(cuts)
    print(f"ступеней снято: {total}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
